const strategies = [
  "类比",
  "举例",
  "联想",
  "对比",
  "因果",
  "转折",
  "细节",
  "场景",
];
export function createReferenceBridges(
  reference: TripleReference,
  words: { word: string; at: number; fact?: string }[],
): ReferenceBridge[] {
  return words.map(({ word, at, fact }, index) => {
    const clean = fact?.replace(/[。！？；，]+$/, "");
    const variant =
      (index +
        [...word].reduce(
          (sum, character) => sum + character.codePointAt(0)!,
          0,
        )) %
      strategies.length;
    const openings = [
      `拿${word}打个比方，${clean}。`,
      `就以${word}为例：${clean}。`,
      `这让我想到${word}，${clean}。`,
      `说到${word}，与其只看表面，我更想注意到${clean}这一点。`,
      `为什么会联想到${word}？因为${clean}。`,
      `看起来${word}离这个话题有点远，不过${clean}。`,
      `借${word}的一个小细节把话说具体：${clean}。`,
      `把${word}放到日常生活里看，${clean}。`,
    ];
    const returns = [
      `不过回到刚才的问题，${reference.mainIdea}`,
      `所以，我想回到这条主线：${reference.mainIdea}`,
      `这个例子只是帮助说明原来的判断：${reference.mainIdea}`,
      `说回原来的话题，${reference.mainIdea}`,
    ];
    return {
      word,
      at,
      strategy: strategies[variant],
      connection: clean
        ? `${openings[variant]}${reference.bridgeLink(word)}`
        : `这个旧词没有匹配的本地桥接片段，不必为了接词另开一个故事。`,
      returnLine: returns[index % returns.length],
    };
  });
}
